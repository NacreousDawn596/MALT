"""Intermediate representation: a compiled compilation unit."""

from __future__ import annotations

from dataclasses import dataclass, field
from types import CodeType
from typing import Any

from . import ast_nodes as ast


@dataclass
class CompilationUnit:
    """The product of compiling a single MATLAB source unit."""

    filename: str
    source: str
    statements: list[ast.Statement]
    generated_source: str
    code: CodeType
    source_map: list[tuple[int, Any]] = field(default_factory=list)
    optimization_level: int = 1
    diagnostics: list[dict] = field(default_factory=list)

    def show_generated(self) -> str:
        header = f"# generated by MALT from {self.filename}"
        return f"{header}\n{self.generated_source}"

    def coverage_report(self) -> str:
        """Summarize which ``for`` loops were JIT-specialized and why others
        fell back."""
        if not self.diagnostics:
            return "no for-loops in this program"
        total = len(self.diagnostics)
        jitted = sum(1 for d in self.diagnostics if d["jit"])
        lines = [
            f"optimization level {self.optimization_level}: "
            f"{jitted}/{total} loop(s) JIT-specialized"
        ]
        for d in self.diagnostics:
            status = "specialized" if d["jit"] else "fell back"
            suffix = "" if d["jit"] else f" — {d['reason']}"
            lines.append(f"  line {d['line']}: for {d['var']} = ... -> {status}{suffix}")
        return "\n".join(lines)
